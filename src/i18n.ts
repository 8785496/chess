export const dictionaries: Record<'ru' | 'en', Dict> = { ru, en };

/** Подстановка {key} в шаблон строки словаря. */
export function format(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

/** Хук-переводчик. */
export function useT(): (key: keyof Dict) => string {
  const lang = useSettings((s) => s.lang);
  return (key) => dictionaries[lang][key];
}

/** Перевод вне компонентов (по текущему языку настроек). */
export function t(key: keyof Dict): string {
  return dictionaries[useSettings.getState().lang][key];
}
